import { describeValue } from '../../../../shared/primitives/assert.js';
import { InvalidPrimitiveError } from '../../../../shared/primitives/invalid-primitive-error.js';
import { assertOpaqueIdentifier } from '../audit-identifiers.js';

/** The kinds of actor an audit record can name. */
export const AUDIT_ACTOR_TYPES = ['user', 'system'] as const;

/** The actor kinds, as persisted and serialized. */
export type AuditActorType = (typeof AUDIT_ACTOR_TYPES)[number];

/**
 * Who performed an audited operation (AUD-001; ADR-003 section 21; ADR-010
 * section 2).
 *
 * Two states, because the architecture has exactly two answers:
 *
 * ```text
 * user    an authenticated user acted — the record names their stable User id
 * system  no user acted — the operation was generated by the system itself
 * ```
 *
 * The distinction is kept *in the record*, not inferred from an absent field:
 * "nobody acted" and "the actor could not be determined" are different facts,
 * and an audit trail that conflates them cannot be trusted to answer "who did
 * this?" (an empty column would be both).
 *
 * Where the user id comes from is the load-bearing rule. It is an
 * application-resolved value — the authenticated principal, or the user a
 * use case already resolved from the authentication boundary — and never a
 * request body, query or header field. The Audit capability cannot enforce that
 * by itself (it cannot see where its caller got the value), which is exactly
 * why the contract it publishes has no tenant field at all and says so in one
 * place: see `application/ports/audit-recorder.port.ts`.
 */
export class AuditActor {
  /** The recorded actor kind. */
  public readonly type: AuditActorType;

  /** The user's stable identity; present exactly when `type` is `user`. */
  public readonly userId?: string;

  private constructor(type: AuditActorType, userId?: string) {
    this.type = type;
    this.userId = userId;
  }

  /** The system acted: no user identity is recorded. */
  public static system(): AuditActor {
    return new AuditActor('system');
  }

  /**
   * An authenticated user acted.
   *
   * @throws InvalidPrimitiveError — the identity is blank, over-long or not an
   * opaque identifier. A malformed actor id is a caller bug, so it is rejected
   * instead of being stored as an unqueryable value.
   */
  public static user(userId: string): AuditActor {
    return new AuditActor('user', assertOpaqueIdentifier(userId, 'AuditActor', 'userId'));
  }

  /**
   * Rebuilds an actor from stored state, re-validating it.
   *
   * @throws InvalidPrimitiveError — an unknown kind, a `user` without an
   * identity, or a `system` carrying one: all three are records the domain
   * cannot represent, and a broken row must fail loudly at the boundary rather
   * than enter the domain as an impossible state.
   */
  public static from(snapshot: {
    readonly type: AuditActorType;
    readonly userId?: string;
  }): AuditActor {
    if (snapshot.type === 'system') {
      if (snapshot.userId !== undefined) {
        throw new InvalidPrimitiveError(
          'AuditActor',
          `a system actor carries no userId but received ${describeValue(snapshot.userId)}`,
        );
      }
      return AuditActor.system();
    }

    if (snapshot.type === 'user') {
      if (snapshot.userId === undefined) {
        throw new InvalidPrimitiveError(
          'AuditActor',
          'a user actor requires a userId but none was given',
        );
      }
      return AuditActor.user(snapshot.userId);
    }

    throw new InvalidPrimitiveError(
      'AuditActor',
      `type must be one of ${AUDIT_ACTOR_TYPES.join(', ')} but received ${describeValue(snapshot.type)}`,
    );
  }

  /** Whether an authenticated user acted. */
  public isUser(): boolean {
    return this.type === 'user';
  }

  /** Whether the system acted, with no user identity. */
  public isSystem(): boolean {
    return this.type === 'system';
  }

  /** Value equality: the same kind and, for a user, the same identity. */
  public equals(other: AuditActor): boolean {
    return other instanceof AuditActor && other.type === this.type && other.userId === this.userId;
  }

  public toString(): string {
    return this.userId === undefined ? 'AuditActor(system)' : `AuditActor(user:${this.userId})`;
  }
}
